//operadores relacionales

var resultado = 20 > 10 ;
console.log(resultado);

var resultado = 10 > 20;
console.log(resultado);

var resultado = 10 == 20; //no tan específico
console.log(resultado);

var resultado = 10 === 20; // Más específico, compara que sea el mismo tipo de variable
console.log(resultado);

var resultado = 10 != 20;
console.log(resultado);

var resultado = 10 >= 20;
console.log(resultado);

var resultado = 10 <= 20;
console.log(resultado);
